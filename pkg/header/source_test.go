func TestSourcePreservesBodyAndIsIdempotent(t *testing.T) {
	body := []byte("// Package example demonstrates headers.\npackage example\n\nvar Value = 1\n")
	got, err := header.Source(body, []byte(notice))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(got, []byte("// Copyright © 2026-present the example authors.")) || !bytes.HasSuffix(got, body) {
		t.Fatalf("header or original body lost:\n%s", got)
	}
	if bytes.Count(got, []byte("Copyright")) != 1 {
		t.Fatalf("duplicate header:\n%s", got)
	}
	again, err := header.Source(got, []byte(notice))
	if err != nil || !bytes.Equal(got, again) {
		t.Fatalf("not idempotent: %v\n%s", err, again)
	}
}

func TestSourceReplacesOwnedHeaders(t *testing.T) {
	old := bytes.ReplaceAll([]byte(notice), []byte("2026-present"), []byte("2025"))
	old = bytes.ReplaceAll(old, []byte("https:"), []byte("http:"))
	block := append([]byte("/*\r\n * "), bytes.ReplaceAll(bytes.TrimSpace(old), []byte("\n"), []byte("\r\n * "))...)
	block = append(block, []byte("\r\n */\r\n\r\n")...)
	line := append([]byte("// "), bytes.ReplaceAll(bytes.TrimSpace(old), []byte("\n"), []byte("\n// "))...)
	line = append(line, []byte("\n\n")...)
	body := []byte("// Package example keeps its documentation.\r\npackage example\r\n")
	for _, prefix := range [][]byte{block, line} {
		got, err := header.Source(append(prefix, body...), []byte(notice))
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.HasSuffix(got, body) || bytes.Count(got, []byte("Copyright")) != 1 || bytes.Contains(got, []byte("http:")) {
			t.Fatalf("replacement damaged source or retained stale notice:\n%s", got)
		}
	}
}

func TestSourceKeepsGeneratedMarkerBuildConstraintsAndPackageDocs(t *testing.T) {
	input, err := os.ReadFile("testdata/generated.go.tmpl")
	if err != nil {
		t.Fatal(err)
	}
	got, err := header.Source(input, []byte(notice))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(got, []byte("// Code generated by example. DO NOT EDIT.\n")) {
		t.Fatalf("generated marker moved away from first line:\n%s", got)
	}
	parsed, err := parser.ParseFile(token.NewFileSet(), "example.go", got, parser.ParseComments)
	if err != nil || !ast.IsGenerated(parsed) || parsed.Doc == nil || parsed.Doc.Text() != "Package example keeps its documentation.\n" {
		t.Fatalf("generated status or package documentation lost: %v\n%s", err, got)
	}
	if !bytes.Contains(got, []byte("//go:build linux\n// +build linux\n\n")) {
		t.Fatalf("build constraints changed:\n%s", got)
	}
	dir := t.TempDir()
	if err := os.WriteFile(dir+"/sample.go", got, 0o644); err != nil {
		t.Fatal(err)
	}
	for _, platform := range []string{"linux", "darwin"} {
		context := build.Default
		context.GOOS = platform
		matches, err := context.MatchFile(dir, "sample.go")
		if err != nil || matches != (platform == "linux") {
			t.Fatalf("build constraint changed for %s: %v, %v", platform, matches, err)
		}
	}
	again, err := header.Source(got, []byte(notice))
	if err != nil || !bytes.Equal(got, again) {
		t.Fatalf("generated source not idempotent: %v\n%s", err, again)
	}
}

func TestSourceRejectsInvalidOrForeignInputs(t *testing.T) {
	foreign := bytes.ReplaceAll([]byte(notice), []byte("example authors"), []byte("someone else"))
	foreign = append([]byte("/*\n"), foreign...)
	foreign = append(foreign, []byte("*/\npackage example\n")...)
	for _, test := range []struct {
		name   string
		source []byte
		notice []byte
	}{
		{
			name:   "foreign owner",
			source: foreign,
			notice: []byte(notice),
		},
		{
			name:   "invalid source",
			source: []byte("package example\nfunc Broken("),
			notice: []byte(notice),
		},
		{
			name:   "empty notice",
			source: []byte("package example\n"),
		},
		{
			name:   "commented template",
			source: []byte("package example\n"),
			notice: []byte("// " + notice),
		},
		{
			name:   "invalid UTF-8",
			source: []byte("package example\n"),
			notice: []byte{0xff},
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			got, err := header.Source(test.source, test.notice)
			if err == nil || got != nil {
				t.Fatalf("invalid input accepted: %v\n%s", err, got)
			}
		})
	}
}

func TestSourceRefusesAdditionalForeignCopyrightInLineNotice(t *testing.T) {
	input := []byte("// Copyright © 2026 the example authors.\n// Licensed under the Apache License, Version 2.0\n// Copyright © 2026 the other authors.\n// limitations under the License.\n\npackage example\n")
	if got, err := header.Source(input, []byte(notice)); err == nil || got != nil {
		t.Fatalf("additional copyright was silently removed: %v\n%s", err, got)
	}
}
